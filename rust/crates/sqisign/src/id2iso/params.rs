//! The precomputed `E0` with the action of its endomorphism ring on the even
//! torsion basis (vendor `precomp/ref/<level>/endomorphism_action.c`).

use super::CurveWithEndomorphisms;
use crate::ec::{Basis, Curve, EcParams, Point};
use crate::gf::{Fp, Fp2, P324, P500, P664};
use crate::mp::Ibz;
use crate::quat::QuatParams;

/// Precomputed `E0` data of a parameter set.
pub trait Id2isoParams: QuatParams + EcParams {
    /// `E0`, its basis of `E0[2^T]` and the action matrices (C
    /// `CURVE_WITH_ENDOMORPHISMS`).
    const CURVE_WITH_ENDOMORPHISMS: CurveWithEndomorphisms<Self>;
}

macro_rules! fp2 {
    ([$($re:literal),*], [$($im:literal),*]) => {
        Fp2 {
            re: Fp::from_montgomery([$($re),*]),
            im: Fp::from_montgomery([$($im),*]),
        }
    };
}

