        variant.deviceTests.values.forEach { deviceTest ->
            buildAndroidNativeKat.forEach { task ->
                deviceTest.sources.jniLibs?.addGeneratedSourceDirectory(task, CMakeBuild::installDir)
            }
        }
    }
}

