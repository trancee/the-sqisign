/** Configures, builds, and installs the SQIsign C core (`native/CMakeLists.txt`) for one target. */
@CacheableTask
abstract class CMakeBuild @Inject constructor(private val exec: ExecOperations) : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sources: ConfigurableFileCollection

    @get:Internal
    abstract val sourceDir: DirectoryProperty

    @get:Input
    abstract val cmakeArguments: ListProperty<String>

    /** Directory holding `cmake` (and optionally `ninja`); empty means "use PATH". */
    @get:Input
    abstract val cmakeBinDir: Property<String>

    /** Path below [installDir] used as the install prefix. */
    @get:Input
    abstract val installSubdir: Property<String>

    @get:Internal
    abstract val buildDir: DirectoryProperty

    @get:OutputDirectory
    abstract val installDir: DirectoryProperty

    @TaskAction
    fun build() {
        val binDir = cmakeBinDir.get().takeIf { it.isNotEmpty() }?.let(::File)
        val cmake = binDir?.resolve("cmake")?.takeIf { it.canExecute() }?.path ?: "cmake"
        val ninja = binDir?.resolve("ninja")?.takeIf { it.canExecute() }
        val build = buildDir.get().asFile
        val root = installDir.get().asFile
        root.deleteRecursively()

        val generator = if (ninja != null) listOf("-G", "Ninja", "-DCMAKE_MAKE_PROGRAM=${ninja.path}") else emptyList()
        exec.exec {
            commandLine(
                listOf(cmake, "-S", sourceDir.get().asFile.path, "-B", build.path) + generator + cmakeArguments.get(),
            )
        }
        exec.exec { commandLine(cmake, "--build", build.path, "--parallel") }
        exec.exec {
            commandLine(cmake, "--install", build.path, "--prefix", root.resolve(installSubdir.get()).path, "--strip")
        }
    }
}

/** Writes the first [vectorsPerSet] vectors of each NIST KAT response file as Kotlin test data. */
@CacheableTask
abstract class GenerateKatVectors : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val responseFiles: ConfigurableFileCollection

    @get:Input
    abstract val vectorsPerSet: Property<Int>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val entries = responseFiles.files.sortedBy { it.name }.flatMap { file ->
            val set = Regex("SQIsign_(p\\d+_\\d+)").find(file.name)!!.groupValues[1].uppercase()
            file.readText().split(Regex("\\r?\\n\\s*\\r?\\n"))
                .map { block ->
                    block.lines().mapNotNull { line ->
                        line.split(" = ", limit = 2).takeIf { it.size == 2 }?.let { it[0].trim() to it[1].trim() }
                    }.toMap()
                }
                .filter { "sm" in it }
                .take(vectorsPerSet.get())
                .map { v ->
                    "KatVector(ParameterSet.$set, ${v["count"]}, \"${v["seed"]}\", ${v["mlen"]}, \"${v["msg"]}\", " +
                        "\"${v["pk"]}\", \"${v["sk"]}\", \"${v["sm"]}\")"
                }
        }
        val out = outputDir.get().asFile.resolve("org/sqisign/KatVectors.kt")
        out.parentFile.mkdirs()
        out.writeText(
            """
            |// Generated by :generateKatVectors from ../KAT/*.rsp. Do not edit.
            |package org.sqisign
            |
            |internal class KatVector(
            |    val parameterSet: ParameterSet,
            |    val count: Int,
            |    val seedHex: String,
            |    val messageLength: Int,
            |    val messageHex: String,
            |    val publicKeyHex: String,
            |    val secretKeyHex: String,
            |    val signedMessageHex: String,
            |)
            |
            |internal val KAT_VECTORS: List<KatVector> = listOf(
            |${entries.joinToString(",\n") { "    $it" }},
            |)
            |
            """.trimMargin(),
        )
    }
}

val repoRoot: Directory = layout.projectDirectory.dir("..")
val nativeDir: Directory = layout.projectDirectory.dir("native")
val nativeSources = files(
    nativeDir,
    repoRoot.file("CMakeLists.txt"),
    repoRoot.dir(".cmake"),
    repoRoot.dir("include"),
    repoRoot.dir("src"),
)

val androidSdkDir: Provider<String> = providers.environmentVariable("ANDROID_HOME")
    .orElse(providers.environmentVariable("ANDROID_SDK_ROOT"))
    .orElse(
        providers.fileContents(layout.projectDirectory.file("local.properties")).asText.map { text ->
            text.lines().firstOrNull { it.startsWith("sdk.dir=") }?.substringAfter("=")?.trim().orEmpty()
        },
    )
    .orElse("")
val ndkVersion: Provider<String> = providers.gradleProperty("sqisign.ndkVersion")

// An explicit sqisign.cmakeBinDir wins; otherwise use the Android SDK's CMake (which ships Ninja), else PATH.
val cmakeBin: Provider<String> = providers.gradleProperty("sqisign.cmakeBinDir").orElse(
    androidSdkDir.zip(providers.gradleProperty("sqisign.cmakeVersion")) { sdk, version ->
        if (sdk.isEmpty()) "" else File(sdk, "cmake/$version/bin").takeIf { it.isDirectory }?.path.orEmpty()
    },
)

fun cmakeInstallDir(taskName: String): Provider<Directory> = layout.buildDirectory.dir("sqisign/out/$taskName")

fun registerCMake(taskName: String, prefixSubdir: String, arguments: List<Provider<String>>) =
    tasks.register<CMakeBuild>(taskName) {
        group = "sqisign native"
        sources.from(nativeSources)
        sourceDir.set(nativeDir)
        cmakeBinDir.set(cmakeBin)
        arguments.forEach { cmakeArguments.add(it) }
        cmakeArguments.add("-DCMAKE_BUILD_TYPE=Release")
        installSubdir.set(prefixSubdir)
        buildDir.set(layout.buildDirectory.dir("sqisign/cmake/$taskName"))
        installDir.set(cmakeInstallDir(taskName))
    }

fun arg(value: String): Provider<String> = provider { value }

// Host JNI library for the JVM target, packaged as a resource under org/sqisign/native/<os>-<arch>/.
val hostOs = System.getProperty("os.name").lowercase().let {
    when {
        it.contains("mac") -> "macos"
        it.contains("win") -> "windows"
        else -> "linux"
    }
}
val hostArch = when (val arch = System.getProperty("os.arch")) {
    "aarch64", "arm64" -> "aarch64"
    "amd64", "x86_64" -> "x86_64"
    else -> arch
}
val jniPlatformDir = when (hostOs) {
    "macos" -> "darwin"
    "windows" -> "win32"
    else -> "linux"
}
val jniJavaHome: Provider<String> = javaToolchains.launcherFor {
    languageVersion.set(JavaLanguageVersion.of(21))
}.map { it.metadata.installationPath.asFile.path.replace('\\', '/') }
val hostBuildType: Provider<String> = providers.gradleProperty("sqisign.hostBuildType")
    .orElse(if (hostArch == "aarch64") "arm64" else "ref")

// Extra, whitespace-separated CMake arguments for the host build, e.g. "-G Ninja -DCMAKE_C_COMPILER=clang" on Windows.
val hostCMakeArgs: Provider<List<String>> = providers.gradleProperty("sqisign.hostCMakeArgs")
    .map { it.trim().split(Regex("\\s+")).filter(String::isNotEmpty) }
    .orElse(emptyList())

fun registerHostJni(taskName: String, resourceDir: String, extraArgs: List<String>) = registerCMake(
    taskName,
    "$resourceDir/$hostOs-$hostArch",
    listOf(
        arg("-DSQISIGN_KMP_OUTPUT=jni"),
        hostBuildType.map { "-DSQISIGN_BUILD_TYPE=$it" },
        jniJavaHome.map { "-DJNI_INCLUDE_DIRS=$it/include;$it/include/$jniPlatformDir" },
    ) + extraArgs.map(::arg),
).also { task -> task.configure { cmakeArguments.addAll(hostCMakeArgs) } }

val buildJvmNative = registerHostJni("buildNativeJvm", "org/sqisign/native", emptyList())

// Test-only JNI library seeded by the NIST CTR-DRBG, used to reproduce the keygen/sign KATs on the JVM.
// Set sqisign.katTests=false to skip them, e.g. when testing prebuilt libraries on a host without a C toolchain.
val katTests: Boolean = providers.gradleProperty("sqisign.katTests").map(String::toBoolean).getOrElse(true)
val buildJvmNativeKat = registerHostJni("buildNativeJvmKat", "org/sqisign/katnative", listOf("-DSQISIGN_KMP_KAT=ON"))

// A directory laid out as org/sqisign/native/<os>-<arch>/<library> (for example, CI artifacts from every platform).
// When set, it replaces the host build as the JVM resource source so one jar can carry all platforms.
val jvmNativeLibs: String? = providers.gradleProperty("sqisign.jvmNativeLibs").orNull

// Android: arm64 uses the optimized arm64 build; x86_64 (emulators, Chromebooks) uses the portable reference build
// because the broadwell build requires ADX/BMI2, which not every x86_64 device or emulator exposes.
val androidMinSdk = 24
val buildAndroidNative = mapOf("arm64-v8a" to "arm64", "x86_64" to "ref").map { (abi, buildType) ->
    registerCMake(
        "buildNativeAndroid" + abi.split('-', '_').joinToString("") { it.replaceFirstChar(Char::uppercase) },
        abi,
        listOf(
            androidSdkDir.zip(ndkVersion) { sdk, ndk ->
                "-DCMAKE_TOOLCHAIN_FILE=$sdk/ndk/$ndk/build/cmake/android.toolchain.cmake"
            },
            arg("-DANDROID_ABI=$abi"),
            arg("-DANDROID_PLATFORM=android-$androidMinSdk"),
            arg("-DSQISIGN_KMP_OUTPUT=jni"),
            arg("-DSQISIGN_BUILD_TYPE=$buildType"),
        ),
    )
}

// Apple: one merged static archive per Kotlin/Native target, embedded into the cinterop klib.
val appleSlices = mapOf(
    "iosArm64" to
        listOf("-DCMAKE_SYSTEM_NAME=iOS", "-DCMAKE_OSX_SYSROOT=iphoneos", "-DCMAKE_OSX_DEPLOYMENT_TARGET=14.0"),
    "iosSimulatorArm64" to
        listOf("-DCMAKE_SYSTEM_NAME=iOS", "-DCMAKE_OSX_SYSROOT=iphonesimulator", "-DCMAKE_OSX_DEPLOYMENT_TARGET=14.0"),
    "macosArm64" to listOf("-DCMAKE_OSX_SYSROOT=macosx", "-DCMAKE_OSX_DEPLOYMENT_TARGET=11.0"),
)
val appleCMakeTaskNames = appleSlices.mapValues { (target, _) ->
    "buildNative${target.replaceFirstChar(Char::uppercase)}"
}
val appleStaticArgs =
    listOf("-DCMAKE_OSX_ARCHITECTURES=arm64", "-DSQISIGN_KMP_OUTPUT=static", "-DSQISIGN_BUILD_TYPE=arm64")
val buildAppleNative = appleSlices.mapValues { (target, sliceArgs) ->
    registerCMake(appleCMakeTaskNames.getValue(target), "", (sliceArgs + appleStaticArgs).map(::arg))
}
// Test-only static archives seeded by the NIST CTR-DRBG, linked into the Apple test binaries.
val buildAppleNativeKat = appleSlices.mapValues { (target, sliceArgs) ->
    registerCMake(
        appleCMakeTaskNames.getValue(target) + "Kat",
        "",
        (sliceArgs + appleStaticArgs + "-DSQISIGN_KMP_KAT=ON").map(::arg),
    )
}

val generateKatVectors = tasks.register<GenerateKatVectors>("generateKatVectors") {
    responseFiles.from(repoRoot.dir("KAT").asFileTree.matching { include("*.rsp") })
    vectorsPerSet.set(3)
    outputDir.set(layout.buildDirectory.dir("generated/kat/kotlin"))
}

kotlin {
    jvmToolchain(21)
    explicitApi()

    // Reference dumps live in api/; checkKotlinAbi runs as part of check, updateKotlinAbi accepts a reviewed change.
    @OptIn(ExperimentalAbiValidation::class)
    abiValidation()

    jvm()

    // drbgTest holds the keygen/sign KAT tests, which need a DRBG-seeded native library (JVM and Apple only).
    @OptIn(ExperimentalKotlinGradlePluginApi::class)
    applyDefaultHierarchyTemplate {
        common {
            group("drbg") {
                withJvm()
                group("apple")
            }
        }
    }

    android {
        namespace = "org.sqisign"
        compileSdk = 36
        minSdk = androidMinSdk
        withDeviceTest {
            instrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        }
    }

    iosArm64()
    iosSimulatorArm64()
    macosArm64()

    // Static framework for Swift consumers: assembleSqiSignXCFramework -> build/XCFrameworks/<buildType>/SqiSign.xcframework
    val xcframework = XCFramework("SqiSign")
    targets.withType<KotlinNativeTarget>().configureEach {
        binaries.framework {
            baseName = "SqiSign"
            isStatic = true
            xcframework.add(this)
        }
        val cmakeTask = buildAppleNative.getValue(name)
        val libDir = cmakeInstallDir(appleCMakeTaskNames.getValue(name)).get().dir("lib").asFile.path
        compilations.getByName("main").cinterops.create("sqisign") {
            definitionFile.set(project.file("src/nativeInterop/cinterop/sqisign.def"))
            packageName = "org.sqisign.cinterop"
            includeDirs(nativeDir.dir("include"))
            extraOpts("-libraryPath", libDir)
            project.tasks.named(interopProcessingTaskName).configure { dependsOn(cmakeTask) }
        }
        val katTask = buildAppleNativeKat.getValue(name)
        val katLibDir = cmakeInstallDir(appleCMakeTaskNames.getValue(name) + "Kat").get().dir("lib").asFile.path
        compilations.getByName("test").cinterops.create("sqisignKat") {
            definitionFile.set(project.file("src/nativeInterop/cinterop/sqisignKat.def"))
            packageName = "org.sqisign.katinterop"
            includeDirs(nativeDir.dir("include"))
            extraOpts("-libraryPath", katLibDir)
            project.tasks.named(interopProcessingTaskName).configure { dependsOn(katTask) }
        }
    }

    sourceSets {
        jvmMain {
            resources.srcDir(jvmNativeLibs?.let(::file) ?: buildJvmNative.flatMap { it.installDir })
        }
        if (katTests) {
            jvmTest {
                resources.srcDir(buildJvmNativeKat.flatMap { it.installDir })
            }
        }
        commonTest {
            kotlin.srcDir(generateKatVectors.flatMap { it.outputDir })
            dependencies {
                implementation(kotlin("test"))
            }
        }
        // Host tests cannot load the Android .so, so the common suite is also compiled into the instrumented device
        // tests. KGP forbids a dependsOn edge between the two source-set trees, hence the shared source directories.
        getByName("androidDeviceTest") {
            kotlin.srcDir("src/commonTest/kotlin")
            kotlin.srcDir(generateKatVectors.flatMap { it.outputDir })
            dependencies {
                implementation(kotlin("test"))
                implementation(libs.androidx.test.runner)
            }
        }
    }
}

