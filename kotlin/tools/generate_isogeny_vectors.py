"""Generate independent normalization, four-isogeny and two-isogeny-chain fixtures."""

import argparse
from functools import lru_cache

from generate_curve_vectors import ORACLES, ROOT, ZERO
from generate_pairing_vectors import pairing_curves
from isogeny_oracle import select_normalization, two_isogeny_chain, velu_four


OUTPUT = ROOT / "src/commonTest/kotlin/ch/trancee/sqisign/ec/IsogenyVectors.kt"
BENCHMARK_OUTPUT = ROOT / "src/jvmBenchmark/kotlin/ch/trancee/sqisign/benchmarks/IsogenyInputs.kt"
SECURITY_BITS = {"p324_3": 128, "p500_27": 192, "p664_17": 256}


def reduce(oracle, coefficient, point, order_exponent):
    return oracle.affine_multiply(coefficient, point, 1 << (oracle.exponent - order_exponent))


def is_singular(oracle, coefficient, four):
    return oracle.affine_add(coefficient, four, four)[0] == ZERO


@lru_cache
def normalization_records(oracle):
    records = []
    for index, (coefficient, basis) in enumerate(pairing_curves(oracle)):
        for generator in basis:
            four = reduce(oracle, coefficient, generator, 2)
            prefix = (oracle.encode_field(coefficient), oracle.encode_affine(four))
            if is_singular(oracle, coefficient, four):
                records.append(":".join(("singular", *prefix, "-")))
                continue
            expected = select_normalization(oracle, coefficient, four)[0]
            records.append(":".join(("generic", *prefix, oracle.encode_field(expected))))
        if index == 0:
            encoded = oracle.encode_field(coefficient)
            for label, order in (("orderTwo", 1), ("orderEight", 3)):
                point = reduce(oracle, coefficient, basis[0], order)
                records.append(":".join((label, encoded, oracle.encode_affine(point), "-")))
            records.append(":".join(("infinity", encoded, "-", "-")))
    return records


@lru_cache
def four_isogeny_records(oracle):
    records = []
    for coefficient, basis in pairing_curves(oracle):
        for generator in basis:
            kernel = reduce(oracle, coefficient, generator, 2)
            if is_singular(oracle, coefficient, kernel):
                continue
            top = oracle.affine_add(coefficient, kernel, kernel)
            points = [*basis, (ZERO, ZERO), None, kernel, top]
            image_coefficient, images = velu_four(oracle, coefficient, kernel, points)
            for point, image in zip(points, images, strict=True):
                records.append(":".join((
                    oracle.encode_field(coefficient), oracle.encode_affine(kernel),
                    oracle.encode_affine(point), oracle.encode_field(image_coefficient),
                    oracle.encode_affine(image))))
    return records


def chain_exponents(oracle, index):
    """The quadratic linear oracle keeps response and maximal lengths to E0 only."""
    lengths = (2, 8, SECURITY_BITS[oracle.identifier])
    return (*lengths, oracle.response_bits, oracle.exponent - 2) if index == 0 else lengths


@lru_cache
def chain_records(oracle):
    records = []
    for index, (coefficient, basis) in enumerate(pairing_curves(oracle)):
        encoded = oracle.encode_field(coefficient)
        for exponent in chain_exponents(oracle, index):
            seed = reduce(oracle, coefficient, basis[0], exponent + 2)
            expected = two_isogeny_chain(oracle, coefficient, seed, exponent)
            records.append(":".join(("generic", encoded, oracle.encode_affine(seed), str(exponent),
                                     oracle.encode_field(expected))))
        if index == 0:
            singular = next(point for point in basis
                            if is_singular(oracle, coefficient, reduce(oracle, coefficient, point, 2)))
            seed = reduce(oracle, coefficient, basis[0], 10)
            for label, point, exponent in (
                ("singular", reduce(oracle, coefficient, singular, 10), 8),
                ("orderTooLow", seed, 10),
                ("orderTooHigh", seed, 6),
                ("infinity", None, 8),
            ):
                records.append(":".join((label, encoded, oracle.encode_affine(point), str(exponent), "-")))
    return records


def content():
    sections = []
    for oracle in ORACLES:
        for suffix, records in (("Normalizations", normalization_records(oracle)),
                                ("FourIsogenies", four_isogeny_records(oracle)),
                                ("Chains", chain_records(oracle))):
            lines = "\n".join(f'        "{record}",' for record in records)
            sections.append(f"    internal val p{oracle.exponent}{suffix}: List<String> = listOf(\n{lines}\n    )\n")
    return (
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// Generated by tools/generate_isogeny_vectors.py; do not edit.\n\n"
        "package ch.trancee.sqisign.ec\n\n"
        "internal object IsogenyVectors {\n" + "\n".join(sections) + "}\n"
    )


def benchmark_content():
    cases = []
    for oracle, parameter in zip(ORACLES, ("NIST_I", "NIST_III", "NIST_V"), strict=True):
        coefficient, basis = pairing_curves(oracle)[0]
        inputs = (reduce(oracle, coefficient, basis[0], SECURITY_BITS[oracle.identifier] + 2),
                  reduce(oracle, coefficient, basis[0], 2), basis[1])
        encodings = "\n".join(f'            "{oracle.encode_affine(point)}",' for point in inputs)
        cases.append(f"        ParameterSet.{parameter} ->\n            listOf(\n{encodings}\n            )")
    return (
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// Generated by tools/generate_isogeny_vectors.py; do not edit.\n\n"
        "package ch.trancee.sqisign.benchmarks\n\n"
        "import ch.trancee.sqisign.ParameterSet\n\n"
        "/** E0 challenge-length seed, order-four kernel and generic point, all affine x-only. */\n"
        "internal fun isogenyInputs(parameter: ParameterSet): List<String> =\n"
        "    when (parameter) {\n" + "\n".join(cases) + "\n    }\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    for output, expected in ((OUTPUT, content()), (BENCHMARK_OUTPUT, benchmark_content())):
        if arguments.check:
            if not output.exists() or output.read_text() != expected:
                raise SystemExit("Isogeny vectors are stale; run tools/generate_isogeny_vectors.py")
        else:
            output.write_text(expected)
    for oracle in ORACLES:
        labels = [record.split(":")[0] for record in normalization_records(oracle)]
        print(f"{oracle.identifier}: {len(labels)} normalizations, "
              f"{len(four_isogeny_records(oracle))} affine Velu images, "
              f"{len(chain_records(oracle))} chains")


if __name__ == "__main__":
    main()
