"""Independent affine group-law oracle for the internal p324_3 x-only curve slice."""

import argparse
import hashlib

from generate_test_vectors import ROOT, fp2_prime_field_square_root, literal


PRIME = 3 * (1 << 324) - 1
ZERO = (0, 0)
ONE = (1, 0)
OUTPUT = ROOT / "src/commonTest/kotlin/ch/trancee/sqisign/ec/CurveVectors.kt"


def add(left, right):
    return tuple((a + b) % PRIME for a, b in zip(left, right))


def negate(value):
    return tuple(-a % PRIME for a in value)


def subtract(left, right):
    return add(left, negate(right))


def multiply(left, right):
    a, b = left
    c, d = right
    return (a * c - b * d) % PRIME, (a * d + b * c) % PRIME


def inverse(value):
    a, b = value
    norm_inverse = pow((a * a + b * b) % PRIME, -1, PRIME)
    return a * norm_inverse % PRIME, -b * norm_inverse % PRIME


def affine_add(coefficient, left, right):
    """Full affine points, using slopes rather than projective x-only formulas."""
    if left is None:
        return right
    if right is None:
        return left
    x1, y1 = left
    x2, y2 = right
    if x1 == x2:
        if y1 == negate(y2):
            return None
        slope_numerator = add(
            add(multiply((3, 0), multiply(x1, x1)),
                multiply((2, 0), multiply(coefficient, x1))), ONE)
        slope = multiply(slope_numerator, inverse(multiply((2, 0), y1)))
    else:
        slope = multiply(subtract(y2, y1), inverse(subtract(x2, x1)))
    x3 = subtract(subtract(subtract(multiply(slope, slope), coefficient), x1), x2)
    return x3, subtract(multiply(slope, subtract(x1, x3)), y1)


def affine_multiply(coefficient, point, scalar):
    result = None
    while scalar:
        if scalar & 1:
            result = affine_add(coefficient, result, point)
        point = affine_add(coefficient, point, point)
        scalar >>= 1
    return result


def sample_field(label):
    block = hashlib.shake_256(label.encode()).digest(82)
    return tuple(int.from_bytes(block[offset:offset + 41], "little") % PRIME
                 for offset in (0, 41))


def sample_point(coefficient, label):
    for counter in range(1024):
        x = sample_field(f"{label} {counter}")
        rhs = multiply(x, add(add(multiply(x, x), multiply(coefficient, x)), ONE))
        y = fp2_prime_field_square_root(*rhs, PRIME)
        if y is not None and y != ZERO and x != ZERO:
            return x, y
    raise RuntimeError("Unable to generate a public curve point")


def encode_field(value):
    return b"".join(component.to_bytes(41, "little") for component in value).hex()


def encode_affine(point):
    return "-" if point is None else encode_field(point[0])


def curve_records():
    scalars = (0, 1, 2, 3, 7, 255, 256, 257, (1 << 196) + 1,
               1 << 327, (1 << 328) - 1, int.from_bytes(b"\xaa" * 41, "little"),
               17, (1 << 328) - 1)
    records = []
    for index, scalar in enumerate(scalars):
        label = f"SQIsign p324_3 public affine curve vector {index}"
        coefficient = ZERO if index % 3 == 0 else sample_field(f"{label} coefficient")
        denominator = sample_field(f"{label} denominator")
        numerator = multiply(coefficient, denominator)
        left = sample_point(coefficient, f"{label} left")
        right = sample_point(coefficient, f"{label} right")
        if index >= 12:
            # Retained JVM workload: A=0, x(P)=2, Q=[2]P, and P-Q=-P.
            coefficient, denominator, numerator = ZERO, ONE, ZERO
            left = ((2, 0), fp2_prime_field_square_root(10, 0, PRIME))
            right = affine_add(coefficient, left, left)
        difference = affine_add(coefficient, left, (right[0], negate(right[1])))
        if difference is None or difference[0] == ZERO:
            raise RuntimeError("Unexpected exceptional public differential-addition input")
        coordinates = []
        for name, point in (("left", left), ("right", right), ("difference", difference)):
            scale = ONE if index >= 12 else sample_field(f"{label} {name} scale")
            coordinates.extend((multiply(point[0], scale), scale))
        records.append(":".join((
            *(encode_field(value) for value in (numerator, denominator, *coordinates)),
            scalar.to_bytes(41, "little").hex(),
            encode_affine(affine_add(coefficient, left, left)),
            encode_affine(affine_add(coefficient, left, right)),
            encode_affine(affine_multiply(coefficient, left, scalar)),
            encode_field(coefficient),
        )))
    return records


def render():
    rows = ",\n".join(f"    {literal(record)}" for record in curve_records())
    return (
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// Generated by tools/generate_curve_vectors.py; do not edit.\n\n"
        "package ch.trancee.sqisign.ec\n\n"
        f"internal val curveP324Vectors: List<String> = listOf(\n{rows},\n)\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    expected = render()
    if arguments.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit("CurveVectors.kt differs; run python3 tools/generate_curve_vectors.py")
        print(f"Validated {len(curve_records())} independent affine p324_3 curve vectors")
    else:
        OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
