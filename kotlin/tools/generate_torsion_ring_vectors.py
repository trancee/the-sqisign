"""Independent Python integer oracles for canonical residues modulo the torsion order."""

import argparse
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/commonTest/kotlin/ch/trancee/sqisign/ec/TorsionRingVectors.kt"
EXPONENTS = (1, 2, 7, 8, 9, 16, 17, 31, 32, 63, 64, 65,
             196, 198, 302, 304, 324, 400, 402, 500, 664)


def sample(exponent, label):
    width = (exponent + 7) // 8
    return int.from_bytes(hashlib.shake_256(label.encode()).digest(width), "little") % (1 << exponent)


def scalar_cases():
    for exponent in EXPONENTS:
        modulus = 1 << exponent
        half = modulus // 2
        pairs = [(0, 0), (0, 1), (1, 0), (1, 1),
                 (modulus - 1, modulus - 1), (modulus - 1, 1),
                 (half, half), (half - 1, (half + 1) % modulus),
                 (modulus - 1, modulus - 2), (3 % modulus, 5 % modulus)]
        pairs += [(sample(exponent, f"torsion-{exponent}-{i}-left"),
                   sample(exponent, f"torsion-{exponent}-{i}-right")) for i in range(12)]
        for left, right in pairs:
            yield exponent, left, right


def encode(exponent, value):
    return value.to_bytes((exponent + 7) // 8, "little").hex()


def scalar_record(exponent, left, right):
    modulus = 1 << exponent
    results = (left, right, (left + right) % modulus,
               (left - right) % modulus, left * right % modulus, -left % modulus)
    comparison = (left > right) - (left < right)
    inverse = encode(exponent, pow(left, -1, modulus)) if left % 2 else "-"
    return ":".join((str(exponent), *(encode(exponent, value) for value in results),
                     str(comparison), inverse))


def matrix_cases():
    for exponent in (1, 2, 8, 9, 198, 304, 324, 402, 500, 664):
        modulus = 1 << exponent
        half = modulus // 2
        matrices = [
            (0, 0, 0, 0), (1, 0, 0, 1), (0, 1, 1, 0),
            (modulus - 1, 0, 0, 1), (modulus - 1, 0, 0, modulus - 1),
            (1, 1, 0, 1), (1, 0, 1, 1),
            (half, 0, (half + 1) % modulus, 1),
            (0, 0, 0, modulus - 1), (0, half, half, 0), (0, 0, 0, half),
            (0, modulus - 1, 0, 1), (half, half, half, half),
            (half - 1, modulus - 1, 1, 1),
        ]
        if exponent == 1:
            matrices += [tuple((bits >> i) & 1 for i in range(4)) for bits in range(16)]
        matrices += [tuple(sample(exponent, f"torsion-matrix-{exponent}-{i}-{j}")
                           for j in range(4)) for i in range(12)]
        for matrix in matrices:
            yield exponent, matrix


def matrix_record(exponent, matrix):
    modulus = 1 << exponent
    a, b, c, d = matrix
    determinant = (a * d - b * c) % modulus
    opposite = tuple(-value % modulus for value in matrix)
    normalized = min(matrix, opposite)
    inverse = "-"
    if determinant % 2:
        factor = pow(determinant, -1, modulus)
        inverse = ":".join(encode(exponent, value * factor % modulus)
                           for value in (d, -b, -c, a))
    return ":".join((str(exponent), *(encode(exponent, value) for value in matrix),
                     encode(exponent, determinant),
                     *(encode(exponent, value) for value in normalized), inverse))


def content():
    records = "\n".join(f'        "{scalar_record(*case)}",' for case in scalar_cases())
    matrices = "\n".join(f'        "{matrix_record(*case)}",' for case in matrix_cases())
    return (
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// Generated by tools/generate_torsion_ring_vectors.py; do not edit.\n\n"
        "package ch.trancee.sqisign.ec\n\n"
        "internal object TorsionRingVectors {\n"
        "    internal val scalars: List<String> = listOf(\n"
        f"{records}\n"
        "    )\n"
        "    internal val matrices: List<String> = listOf(\n"
        f"{matrices}\n"
        "    )\n"
        "}\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    expected = content()
    if arguments.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit("Torsion ring vectors are stale; run tools/generate_torsion_ring_vectors.py")
    else:
        OUTPUT.write_text(expected)
    print(f"Verified {sum(1 for _ in scalar_cases())} scalar and "
          f"{sum(1 for _ in matrix_cases())} matrix records")


if __name__ == "__main__":
    main()
