#!/usr/bin/env bash
# Prints the repository-root Package.swift of a release (ADR 0005): SqiSignKit over the C backend's SqiSign.xcframework.
#   release-manifest.sh <url> <checksum>   binary target downloaded from a release
#   release-manifest.sh <path>             binary target from a local .xcframework.zip, relative to the repository root
set -euo pipefail

if [[ $# -eq 2 ]]; then
  binary="url: \"$1\",
            checksum: \"$2\""
elif [[ $# -eq 1 ]]; then
  binary="path: \"$1\""
else
  echo "usage: $0 <url> <checksum> | $0 <path>" >&2
  exit 2
fi

cat <<EOF
// swift-tools-version:5.9
// Generated by kotlin/swift/release-manifest.sh for a release tag; kotlin/swift/Package.swift is the development package.
import PackageDescription

let package = Package(
    name: "SqiSignKit",
    platforms: [.iOS(.v14), .macOS(.v11)],
    products: [
        .library(name: "SqiSignKit", targets: ["SqiSignKit"]),
    ],
    targets: [
        .binaryTarget(
            name: "SqiSign",
            $binary),
        .target(
            name: "SqiSignKit",
            dependencies: ["SqiSign"],
            path: "kotlin/swift/Sources/SqiSignKit",
            swiftSettings: [.enableExperimentalFeature("StrictConcurrency")]),
    ]
)
EOF
